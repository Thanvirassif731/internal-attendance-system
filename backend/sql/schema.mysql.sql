CREATE TABLE IF NOT EXISTS `Team` (
  `id` VARCHAR(191) PRIMARY KEY, `name` VARCHAR(191) NOT NULL UNIQUE,
  `description` TEXT NULL, `leadId` VARCHAR(191) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  INDEX (`leadId`)
);
CREATE TABLE IF NOT EXISTS `User` (
  `id` VARCHAR(191) PRIMARY KEY, `name` VARCHAR(191) NOT NULL,
  `username` VARCHAR(191) NOT NULL UNIQUE, `email` VARCHAR(191) NOT NULL UNIQUE,
  `password` VARCHAR(255) NOT NULL, `role` VARCHAR(32) NOT NULL DEFAULT 'USER',
  `status` VARCHAR(32) NOT NULL DEFAULT 'ACTIVE', `designation` VARCHAR(191) NULL,
  `rollNumber` VARCHAR(191) NULL UNIQUE, `avatar` VARCHAR(191) NULL, `teamId` VARCHAR(191) NULL,
  `lastLogin` DATETIME(3) NULL, `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  INDEX (`email`), INDEX (`username`), INDEX (`teamId`),
  CONSTRAINT `User_team_fk` FOREIGN KEY (`teamId`) REFERENCES `Team`(`id`) ON DELETE SET NULL
);
ALTER TABLE `Team` ADD CONSTRAINT `Team_lead_fk` FOREIGN KEY (`leadId`) REFERENCES `User`(`id`) ON DELETE SET NULL;
CREATE TABLE IF NOT EXISTS `Task` (
  `id` VARCHAR(191) PRIMARY KEY, `title` VARCHAR(191) NOT NULL, `description` TEXT NULL,
  `priority` VARCHAR(32) NOT NULL DEFAULT 'MEDIUM', `status` VARCHAR(32) NOT NULL DEFAULT 'PENDING',
  `progress` INT NOT NULL DEFAULT 0, `dueDate` DATETIME(3) NULL, `completedAt` DATETIME(3) NULL,
  `userId` VARCHAR(191) NOT NULL, `createdById` VARCHAR(191) NULL, `teamId` VARCHAR(191) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  INDEX (`userId`), INDEX (`status`), INDEX (`teamId`),
  FOREIGN KEY (`userId`) REFERENCES `User`(`id`) ON DELETE CASCADE,
  FOREIGN KEY (`createdById`) REFERENCES `User`(`id`) ON DELETE SET NULL,
  FOREIGN KEY (`teamId`) REFERENCES `Team`(`id`) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS `Announcement` (
  `id` VARCHAR(191) PRIMARY KEY, `title` VARCHAR(191) NOT NULL, `content` TEXT NOT NULL,
  `priority` VARCHAR(32) NOT NULL DEFAULT 'IMPORTANT', `expiryDate` DATETIME(3) NULL,
  `isReposted` BOOLEAN NOT NULL DEFAULT FALSE, `originalId` VARCHAR(191) NULL,
  `authorId` VARCHAR(191) NOT NULL, `attachment` VARCHAR(191) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  INDEX (`authorId`), INDEX (`priority`), FOREIGN KEY (`authorId`) REFERENCES `User`(`id`) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS `Attendance` (
  `id` VARCHAR(191) PRIMARY KEY, `userId` VARCHAR(191) NOT NULL, `date` VARCHAR(10) NOT NULL,
  `checkInTime` VARCHAR(32) NULL, `checkOutTime` VARCHAR(32) NULL, `status` VARCHAR(32) NOT NULL DEFAULT 'PRESENT',
  `notes` TEXT NULL, `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY `Attendance_user_date` (`userId`,`date`), INDEX (`date`), INDEX (`userId`),
  FOREIGN KEY (`userId`) REFERENCES `User`(`id`) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS `LeaveRequest` (
  `id` VARCHAR(191) PRIMARY KEY, `userId` VARCHAR(191) NOT NULL, `leaveDate` VARCHAR(10) NOT NULL,
  `reason` VARCHAR(191) NOT NULL, `description` TEXT NULL, `status` VARCHAR(32) NOT NULL DEFAULT 'PENDING',
  `reviewedById` VARCHAR(191) NULL, `reviewedAt` DATETIME(3) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  INDEX (`userId`), INDEX (`status`), FOREIGN KEY (`userId`) REFERENCES `User`(`id`) ON DELETE CASCADE,
  FOREIGN KEY (`reviewedById`) REFERENCES `User`(`id`) ON DELETE SET NULL
);
